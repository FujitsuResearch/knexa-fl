    def _simplify_paper_materials(self, exp_dir: Path):
        """
        Simplify the paper materials structure, keeping only essential files
        """
        paper_dir = exp_dir / "paper_materials"
        if not paper_dir.exists():
            return
            
        logger.info("📄 Simplifying paper materials structure...")
        
        # Essential directories to keep
        essential_dirs = ["data", "figures", "tables"]
        essential_files = ["MASTER_SUMMARY.json", "README.md"]
        
        # Create simplified structure
        simplified_dir = exp_dir / "paper_materials_simplified"
        simplified_dir.mkdir(exist_ok=True)
        
        # Copy essential content
        for essential_dir in essential_dirs:
            src_dir = paper_dir / essential_dir
            if src_dir.exists():
                dst_dir = simplified_dir / essential_dir
                shutil.copytree(src_dir, dst_dir, dirs_exist_ok=True)
                
