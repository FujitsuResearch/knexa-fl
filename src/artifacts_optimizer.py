    def _update_latest_symlink(self, exp_dir: Path):
        """Update 'latest' symlink to point to most recent experiment"""
        
        latest_symlink = self.base_dir / "latest"
        
        # Remove existing symlink
        if latest_symlink.exists() or latest_symlink.is_symlink():
            latest_symlink.unlink()
        
        # Create new symlink
        try:
            relative_path = exp_dir.relative_to(self.base_dir)
            latest_symlink.symlink_to(relative_path)
            logger.info(f"🔗 Updated latest symlink: {latest_symlink} -> {exp_dir.name}")
        except Exception as e:
            logger.warning(f"Could not create latest symlink: {e}")
    
    def compress_large_artifacts(self, exp_dir: Path):
        """Compress large artifacts using zstd for storage efficiency"""
        
        logger.info("🗜️ Compressing large artifacts...")
        
        # Compress code generation archive
        archive_dir = exp_dir / "code_generation" / "archive"
        if archive_dir.exists():
            json_files = list(archive_dir.glob("*.json"))
            
            if len(json_files) > 10:  # Only compress if many files
                compressed_file = archive_dir / "compressed_logs.json.zst"
                
                # Combine all JSON files into compressed archive
                combined_data = []
                for json_file in json_files:
                    try:
                        with open(json_file, 'r') as f:
                            data = json.load(f)
                            data['_original_filename'] = json_file.name
                            combined_data.append(data)
                    except Exception as e:
                        logger.warning(f"Could not read {json_file}: {e}")
                
                # Compress using zstd
                if combined_data:
                    cctx = zstd.ZstdCompressor(level=3)
                    json_str = json.dumps(combined_data)
                    compressed_data = cctx.compress(json_str.encode('utf-8'))
                    
                    with open(compressed_file, 'wb') as f:
                        f.write(compressed_data)
                    
                    # Remove original files after successful compression
                    for json_file in json_files:
                        json_file.unlink()
                    
                    self.cleanup_log.append(f"Compressed {len(json_files)} JSON files to {compressed_file.name}")
    
    def _consolidate_code_generation_logs(self, exp_dir: Path):
        """
        Consolidate individual code generation JSON files into summary files
        """
        code_gen_dir = exp_dir / "code_generation"
        if not code_gen_dir.exists():
            return
            
        logger.info("📝 Consolidating code generation logs...")
        
        # Group files by client and problem type
        client_logs = {}
        
        for json_file in code_gen_dir.glob("*.json"):
            try:
                with open(json_file, 'r') as f:
                    data = json.load(f)
                    
                # Extract client ID and problem info from filename
                filename = json_file.stem
                parts = filename.split('_')
                if len(parts) >= 3:
                    client_id = parts[1]
                    problem_id = parts[2]
                    
                    if client_id not in client_logs:
                        client_logs[client_id] = {}
                    
                    if problem_id not in client_logs[client_id]:
                        client_logs[client_id][problem_id] = []
                        
                    client_logs[client_id][problem_id].append({
                        'timestamp': data.get('timestamp', ''),
                        'generated_code': data.get('generated_code', ''),
                        'test_result': data.get('test_result', {}),
                        'execution_time': data.get('execution_time', 0),
                        'filename': json_file.name
                    })
                    
            except Exception as e:
                logger.warning(f"Failed to process {json_file}: {e}")
                continue
        
        # Create consolidated summary files
        summary_dir = code_gen_dir / "summaries"
        summary_dir.mkdir(exist_ok=True)
        
        for client_id, client_data in client_logs.items():
            summary_file = summary_dir / f"client_{client_id}_summary.json"
            
            # Calculate summary statistics
            total_problems = len(client_data)
            total_attempts = sum(len(attempts) for attempts in client_data.values())
            successful_attempts = 0
            
            for problem_attempts in client_data.values():
                for attempt in problem_attempts:
                    if attempt.get('test_result', {}).get('passed', False):
                        successful_attempts += 1
            
            summary = {
                'client_id': client_id,
                'optimization_timestamp': datetime.now().isoformat(),
                'statistics': {
                    'total_problems': total_problems,
                    'total_attempts': total_attempts,
                    'successful_attempts': successful_attempts,
                    'success_rate': successful_attempts / total_attempts if total_attempts > 0 else 0.0
                },
                'detailed_results': client_data
            }
            
            with open(summary_file, 'w') as f:
                json.dump(summary, f, indent=2)
                
        # Move original files to archive
        archive_dir = code_gen_dir / "archive"
        archive_dir.mkdir(exist_ok=True)
        
        for json_file in code_gen_dir.glob("*.json"):
            if json_file.parent.name == "code_generation":  # Only move files in root of code_generation
                shutil.move(str(json_file), str(archive_dir / json_file.name))
                
        self.cleanup_log.append(f"Consolidated {len(client_logs)} clients' code generation logs")
    
    def _remove_duplicate_results(self, exp_dir: Path):
        """
        Remove duplicate result files keeping only the most comprehensive version
        """
        logger.info("🗑️ Removing duplicate result files...")
        
        # Keep JSON, remove PKL duplicates
        json_files = list(exp_dir.glob("*.json"))
        pkl_files = list(exp_dir.glob("*.pkl"))
        
        for pkl_file in pkl_files:
            json_equivalent = exp_dir / (pkl_file.stem + ".json")
            if json_equivalent.exists():
                pkl_file.unlink()
                self.cleanup_log.append(f"Removed duplicate PKL file: {pkl_file.name}")
                
        # Remove duplicate round results - keep only the summary
        round_results_dir = exp_dir / "raw_data" / "round_results"
        if round_results_dir.exists():
            # Keep only the latest/summary round results
            round_files = list(round_results_dir.glob("round_*.json"))
            if len(round_files) > 3:  # Keep only first, middle, and last rounds
                round_files.sort()
                keep_files = [round_files[0], round_files[len(round_files)//2], round_files[-1]]
                
                for round_file in round_files:
                    if round_file not in keep_files:
                        round_file.unlink()
                        self.cleanup_log.append(f"Removed intermediate round file: {round_file.name}")
    
    def _optimize_plots_structure(self, exp_dir: Path):
        """
        Optimize plots directory by removing duplicates and organizing by category
        """
        logger.info("📊 Optimizing plots structure...")
        
        plots_dir = exp_dir / "plots"
        if not plots_dir.exists():
            return
        
        # If plots directory is already organized (has subdirectories), skip
        subdirs = [d for d in plots_dir.iterdir() if d.is_dir()]
        if len(subdirs) > 0:
            logger.info("Plots already organized in subdirectories")
            return
            
        # Create organized structure
        categories = {
            'performance': ['pass_at_k', 'codebleu', 'performance'],
            'training': ['loss', 'training', 'convergence'],
            'communication': ['communication', 'bandwidth', 'latency'],
            'system': ['memory', 'gpu', 'dashboard']
        }
        
        # Organize plots by category
        for category, keywords in categories.items():
            category_dir = plots_dir / category
            category_dir.mkdir(exist_ok=True)
            
            # Find and move relevant plots
            for plot_file in plots_dir.glob("*.png"):
                filename_lower = plot_file.name.lower()
                if any(keyword in filename_lower for keyword in keywords):
                    shutil.move(str(plot_file), str(category_dir / plot_file.name))
    
    def _cleanup_temporary_files(self, exp_dir: Path):
        """
        Clean up temporary and cache files
        """
        logger.info("🧹 Cleaning up temporary files...")
        
        # Common temporary file patterns
        temp_patterns = [
            "*.tmp",
            "*.cache", 
            "*_temp_*",
            "__pycache__",
            ".DS_Store"
        ]
        
        cleanup_count = 0
        for pattern in temp_patterns:
            for temp_file in exp_dir.rglob(pattern):
                try:
                    if temp_file.is_file():
                        temp_file.unlink()
                        cleanup_count += 1
                    elif temp_file.is_dir() and pattern == "__pycache__":
                        shutil.rmtree(temp_file)
                        cleanup_count += 1
                except Exception as e:
                    logger.warning(f"Failed to remove {temp_file}: {e}")
                    
        self.cleanup_log.append(f"Removed {cleanup_count} temporary files")
    
    def _create_optimization_summary(self, exp_dir: Path):
        """
        Create a summary of the optimization process
        """
        summary = {
            'optimization_timestamp': datetime.now().isoformat(),
            'experiment_directory': str(exp_dir),
            'optimizations_performed': self.cleanup_log,
            'directory_structure_after_optimization': self._get_directory_structure(exp_dir)
        }
        
        with open(exp_dir / "OPTIMIZATION_SUMMARY.json", 'w') as f:
            json.dump(summary, f, indent=2)
            
        logger.info(f"📋 Created optimization summary with {len(self.cleanup_log)} optimizations")
    
    def _get_directory_structure(self, directory: Path, max_depth: int = 3) -> Dict[str, Any]:
        """
        Get simplified directory structure for documentation
        """
        def scan_dir(path: Path, current_depth: int = 0) -> Dict[str, Any]:
            if current_depth >= max_depth:
                return {"...": "max_depth_reached"}
                
            structure = {}
            try:
                for item in path.iterdir():
                    if item.is_dir():
                        structure[f"{item.name}/"] = scan_dir(item, current_depth + 1)
                    else:
                        # Just record file count for directories with many files
                        if "files" not in structure:
                            structure["files"] = 0
                        structure["files"] += 1
            except PermissionError:
                structure["error"] = "permission_denied"
                
            return structure
            
        return scan_dir(directory)


