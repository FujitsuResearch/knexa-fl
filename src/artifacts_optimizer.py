    def _optimize_plots_structure(self, exp_dir: Path):
        """
        Optimize plots directory by removing duplicates and organizing by category
        """
        logger.info("📊 Optimizing plots structure...")
        
        plots_dir = exp_dir / "plots"
        report_dir = exp_dir / "report"
        
        if not plots_dir.exists():
            return
            
        # Create organized structure
        organized_plots = exp_dir / "plots_organized"
        organized_plots.mkdir(exist_ok=True)
        
        categories = {
            'performance': ['pass_at_k', 'codebleu', 'performance'],
            'training': ['loss', 'training', 'convergence'],
            'communication': ['communication', 'bandwidth', 'latency'],
            'system': ['memory', 'gpu', 'dashboard']
        }
        
        # Organize plots by category
        for category, keywords in categories.items():
            category_dir = organized_plots / category
            category_dir.mkdir(exist_ok=True)
            
            # Find and move relevant plots
            for plot_file in plots_dir.glob("*.png"):
                filename_lower = plot_file.name.lower()
                if any(keyword in filename_lower for keyword in keywords):
                    shutil.copy2(plot_file, category_dir / plot_file.name)
                    
        # Remove duplicate plots from report directory if they exist in plots
        if report_dir.exists():
            for report_plot in report_dir.glob("*.png"):
                plots_equivalent = plots_dir / report_plot.name
                if plots_equivalent.exists():
                    report_plot.unlink()
                    self.cleanup_log.append(f"Removed duplicate plot from report: {report_plot.name}")
                    
        # Archive original plots directory
        if plots_dir.exists():
            shutil.move(str(plots_dir), str(exp_dir / "plots_archive"))
            
        # Rename organized to main
        organized_plots.rename(plots_dir)
        
    def _cleanup_temporary_files(self, exp_dir: Path):
        """
        Clean up temporary and cache files
        """
        logger.info("🧹 Cleaning up temporary files...")
        
        # Common temporary file patterns
        temp_patterns = [
            "*.tmp",
            "*.cache", 
            "*_temp_*",
            "*.log",  # Keep only main log files
            "__pycache__",
            ".DS_Store"
        ]
        
        cleanup_count = 0
        for pattern in temp_patterns:
            for temp_file in exp_dir.rglob(pattern):
                try:
                    if temp_file.is_file():
                        temp_file.unlink()
                        cleanup_count += 1
                    elif temp_file.is_dir() and pattern == "__pycache__":
                        shutil.rmtree(temp_file)
                        cleanup_count += 1
                except Exception as e:
                    logger.warning(f"Failed to remove {temp_file}: {e}")
                    
        self.cleanup_log.append(f"Removed {cleanup_count} temporary files")
        
